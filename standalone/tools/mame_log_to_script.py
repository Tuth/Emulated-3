#!/usr/bin/env python3
"""Convert a MAME capture (error.log with EIII_MON_SCAN_PUSH lines and debugger 'XSW cyc=N d=XX' reads of 0xFA0000)
into a standalone --script that reproduces the same input at the same emulated instants.

MAME applies ioport changes at 60 Hz frame updates: scanner bytes are pushed at the logged cycle; an extra-switch
change becomes visible at the frame boundary lying between the last poll that saw the old value and the first poll
that saw the new one.  Usage: mame_log_to_script.py error.log [extra lines...] > script.txt
"""
import math
import re
import sys

CPU_HZ = 10_000_000
FRAME = 1.0 / 60.0


def main():
    txt = open(sys.argv[1], errors='ignore').read()
    out = ['# generated by tools/mame_log_to_script.py from ' + sys.argv[1]]
    for m in re.finditer(r'EIII_MON_SCAN_PUSH cyc=(\d+) byte=([0-9A-F]{2})', txt):
        out.append('%.7f scan %s' % (int(m.group(1)) / CPU_HZ, m.group(2)))
    reads = [(int(a), int(b, 16)) for a, b in re.findall(r'XSW cyc=(\d+) d=([0-9A-F]{2})', txt)]
    names = {0x01: 'Erase', 0x02: 'Record', 0x08: 'Enter', 0x10: 'Mode', 0x20: 'Management', 0x40: 'Master', 0x80: 'Sample'}
    for (c0, v0), (c1, v1) in zip(reads, reads[1:]):
        if v0 == v1:
            continue
        t0, t1 = c0 / CPU_HZ, c1 / CPU_HZ
        edge = math.floor(t0 / FRAME + 1) * FRAME          # first frame boundary after the old-value poll
        if not t0 < edge <= t1:
            sys.exit('no frame boundary between polls at %d and %d' % (c0, c1))
        for bit, name in names.items():
            if (v0 ^ v1) & bit:
                out.append('%.9f extra-%s %s' % (edge, 'down' if v1 & bit else 'up', name))
    out += sys.argv[2:]

    def key(line):
        try:
            return float(line.split()[0])
        except ValueError:
            return -1.0
    print('\n'.join(sorted(out, key=key)))


if __name__ == '__main__':
    main()

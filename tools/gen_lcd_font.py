import sys
lines=[l.strip() for l in ART.strip().split('\n') if l.strip()]
glyph={}
for i in range(0,len(lines),2):
    code=int(lines[i],16); rows=lines[i+1].split('|')
    assert len(rows)==7 and all(len(r)==5 for r in rows), lines[i]
    glyph[code]=[int(r.replace('#','1').replace('.','0'),2) for r in rows]+[0]
assert sorted(glyph)==list(range(0x20,0x80))
out=['// Generated by tools/gen_lcd_font.py: original 5x7 character set (rows 0-6, row 7 = cursor line), codes 0x20-0x7F,',
     '// HD44780 A00 layout (0x5C yen, 0x7E right arrow, 0x7F left arrow).  Bit 4 = leftmost dot.']
for c in range(0x20,0x80):
    out.append('{ '+', '.join('0x%02X'%b for b in glyph[c])+' },  // %02X %s'%(c, repr(chr(c)) if c<0x7e else ''))
open(sys.argv[1] if len(sys.argv)>1 else 'eiii_lcd_font.inc','w').write('\n'.join(out)+'\n')
